AS

select 
	pg.id_prodotti_gas
	,fpg.id_famiglia
	,fpg.codice_famiglia
	,fpg.nome_commerciale
	,(SELECT string_agg(descr_componente, ',') FROM v_prodotti_gas_comp as pgc where pgc.id_famiglia=pg.id_famiglia) as composizione
	,pg.descr_famiglia_allestimento
