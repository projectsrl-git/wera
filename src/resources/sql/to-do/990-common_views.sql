on pg.id_famiglia=fpg.id_famiglia
;




-- view [V_SPECIFICHE_ALLESTIMENTI]
DROP VIEW IF exists V_SPECIFICHE_ALLESTIMENTI;

CREATE VIEW V_SPECIFICHE_ALLESTIMENTI
AS

select 
 SA.ID_SPECIFICA
 ,SA.ID_FAMIGLIA 
 ,AL.ID_ALLESTIMENTO
 ,AL.ORDINE
 ,ALS.CODICE AS CODICE_ALLESTIMENTO
 ,ALS.DESCRIZIONE AS TIPOLOGIA_ALLESTIMENTO
 ,AL.CARATTERISTICA AS CARATTERISTICA
 ,COALESCE(SA.DESCRIZIONE,'-') as DESCRIZIONE
 ,AL.FL_MATERIALE
 ,SA.ID_MATERIALE
 ,MAT.DESCRIZIONE AS DESCRIZIONE_MATERIALE
 ,MAT.CODICE_SAP
from ALLESTIMENTI as AL
LEFT OUTER join SPECIFICHE_ALLESTIMENTO as SA
ON AL.ID_ALLESTIMENTO = SA.ID_ALLESTIMENTO
LEFT OUTER JOIN FAMIGLIA_PRODOTTI_GAS AS FPG
ON FPG.ID_FAMIGLIA=SA.ID_FAMIGLIA 
LEFT OUTER JOIN PARAMETRI AS ALS 
ON ALS.CODICE = AL.CODICE_ALLESTIMENTO AND ALS.DOMINIO='ALS'
LEFT OUTER JOIN MATERIALI AS MAT 
ON SA.ID_MATERIALE = MAT.ID_MATERIALE 
;



